"""Every New Relic output produced from the shipped fixtures, pinned by sha256.

A change to an emitter that alters any byte here is deliberate and visible: the hashes in
tests/fixtures/emitter-output-hashes.json must be regenerated by a person who has read the diff.
"""

import hashlib
import json
from pathlib import Path

import pytest
from typer.testing import CliRunner

from importer.cli import app

FIXTURES = Path(__file__).parent / "fixtures"
HASHES = FIXTURES / "emitter-output-hashes.json"
ALERT_SOURCES = {
    "cloudwatch": "cloudwatch",
    "cloudwatch-real": "cloudwatch",
    "gcp": "gcp",
    "dynatrace": "dynatrace",
    "grafana": "grafana",
}


def _run(args: list[str]) -> None:
    done = CliRunner().invoke(app, args)
    assert done.exit_code == 0, done.output


def _digests(folder: Path) -> dict[str, str]:
    return {
        str(p.relative_to(folder)): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(folder.rglob("*"))
        if p.is_file()
    }


def collect(work: Path) -> dict[str, dict[str, str]]:
    """Run every conversion offline into `work` and hash each file written."""
    out: dict[str, dict[str, str]] = {}
    for fixture, source in ALERT_SOURCES.items():
        target = work / fixture
        _run(["convert", "--source", source, "--in", str(FIXTURES / fixture), "--out", str(target)])
        out[f"convert/{fixture}"] = _digests(target)
    aws = FIXTURES / "notifications-aws"
    _run(
        ["convert-notifications", "--topics", str(aws / "topic-input.json")]
        + ["--alerts", str(work / "cloudwatch"), "--out", str(work / "n-aws")]
    )
    out["notifications/aws"] = _digests(work / "n-aws")
    _run(
        ["convert-notifications", "--source", "dynatrace", "--topics", str(FIXTURES / "dynatrace")]
        + ["--out", str(work / "n-dt")]
    )
    out["notifications/dynatrace"] = _digests(work / "n-dt")
    gcp = FIXTURES / "gcp-notifications"
    _run(["convert", "--source", "gcp", "--in", str(gcp / "policies"), "--out", str(work / "g-a")])
    _run(
        ["convert-gcp-notifications", "--channels", str(gcp / "channels")]
        + ["--alerts", str(work / "g-a"), "--out", str(work / "n-gcp")]
    )
    out["notifications/gcp"] = _digests(work / "n-gcp")
    return out


@pytest.fixture(scope="module")
def produced(tmp_path_factory: pytest.TempPathFactory) -> dict[str, dict[str, str]]:
    return collect(tmp_path_factory.mktemp("hashes"))


def test_every_output_set_is_pinned(produced: dict[str, dict[str, str]]) -> None:
    pinned = json.loads(HASHES.read_text())
    assert sorted(produced) == sorted(pinned)


@pytest.mark.parametrize(
    "group",
    [
        *(f"convert/{f}" for f in ALERT_SOURCES),
        "notifications/aws",
        "notifications/dynatrace",
        "notifications/gcp",
    ],
)
def test_output_bytes_are_unchanged(produced: dict[str, dict[str, str]], group: str) -> None:
    pinned = json.loads(HASHES.read_text())[group]
    assert produced[group] == pinned
